#!/usr/bin/env python
"""Build demo-site/data.js from committed results/.

    python demo-site/build.py          # from the repo root
    python demo-site/build.py --check  # exit 1 if data.js is stale

Renders exactly the committed deterministic benchmark, the recorded live-LLM
run, the per-task execution traces, and the attack outcomes that
scripts/run_jail_attacks.py recorded in results/jail_attack_evidence.json.
The page computes every number it shows from this data. The output is
byte-stable (LF line endings), so CI can require that a fresh build matches
the committed data.js.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"


def load(name: str):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


traces = {}
for path in sorted((RESULTS / "benchmark_traces").glob("*.json")):
    t = load(str(path.relative_to(RESULTS)))
    traces[t["task_id"]] = {
        "task_description": t.get("task_description", ""),
        "state": t.get("state"),
        "steps_used": t.get("steps_used"),
        "replans": t.get("replans"),
        "files_changed": t.get("files_changed", []),
        "test_results": t.get("test_results", []),
        "actions": t.get("actions", []),
        "observations": t.get("observations", []),
    }

data = {
    "benchmark": load("benchmark_results.json"),
    "llm_benchmark": load("llm_benchmark_results.json"),
    "traces": traces,
    "attacks": load("jail_attack_evidence.json"),
}

out = Path(__file__).resolve().parent / "data.js"
content = (
    "// Generated by demo-site/build.py from committed results/ - do not hand-edit.\n"
    "window.DATA = " + json.dumps(data, indent=1) + ";\n"
)
if "--check" in sys.argv[1:]:
    current = out.read_text(encoding="utf-8").replace("\r\n", "\n") if out.exists() else ""
    if current != content:
        sys.exit("demo-site/data.js is stale: run python demo-site/build.py")
    print("demo-site/data.js is current")
    sys.exit(0)
with out.open("w", encoding="utf-8", newline="\n") as handle:
    handle.write(content)
print(f"wrote {out} ({out.stat().st_size} bytes)")
